function generateAsciiArt() {
    const text = document.getElementById('ascii-input').value || ' ';
    const fontName = document.getElementById('ascii-font').value;
    const font = asciiFonts[fontName] || asciiFonts.standard;
    const lines = ['', '', '', '', fontName === 'banner' ? '' : ''];
    const upperText = text.toUpperCase();
    
    const lineCount = fontName === 'banner' ? 7 : 5;
    
    for (let char of upperText) {
        const charArt = font.chars[char] || font.chars[' '] || Array(lineCount).fill('     ');
        for (let i = 0; i < lineCount; i++) {
            lines[i] += (charArt[i] || '     ') + '  ';
        }
    }
    
    document.getElementById('ascii-result').textContent = lines.join('\n');
}
